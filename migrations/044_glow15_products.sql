CREATE TABLE IF NOT EXISTS glow15_products (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  journey_id text NOT NULL,
  product_name text NOT NULL,
  brand text,
  category text NOT NULL,
  format text,
  barcode text,
  ingredients jsonb NOT NULL DEFAULT '[]'::jsonb,
  visible_text text,
  fit_score integer,
  safety_level text,
  effectiveness_level text,
  suitability_level text,
  fit_reasons jsonb NOT NULL DEFAULT '[]'::jsonb,
  cautions jsonb NOT NULL DEFAULT '[]'::jsonb,
  best_for jsonb NOT NULL DEFAULT '[]'::jsonb,
  avoid_if jsonb NOT NULL DEFAULT '[]'::jsonb,
  alternative_profile jsonb NOT NULL DEFAULT '[]'::jsonb,
  routine_role text,
  application text,
  scan_confidence text,
  source text NOT NULL DEFAULT 'glow15_scanner',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
)