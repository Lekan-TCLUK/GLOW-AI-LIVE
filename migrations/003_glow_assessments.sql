CREATE TABLE glow_assessments (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  journey_id UUID NULL REFERENCES glow_journeys(id),
  session_id TEXT NOT NULL,
  assessment_type TEXT NOT NULL CHECK (assessment_type IN ('INITIAL', 'DAY30')),
  assessment_status TEXT NOT NULL CHECK (assessment_status IN ('QUALITY_RETRY', 'REJECTED', 'VALID', 'FAILED')),
  assessment_version TEXT NOT NULL,
  vision_version TEXT NOT NULL,
  scoring_version TEXT NOT NULL,
  calibration_version TEXT NOT NULL,
  quality_gate_version TEXT NOT NULL,
  safety_version TEXT NOT NULL,
  photo_quality_status TEXT NOT NULL CHECK (photo_quality_status IN ('PASS', 'RETRY', 'REJECT')),
  photo_quality_reason_codes JSONB NOT NULL DEFAULT '[]'::jsonb,
  assessment_confidence TEXT NULL CHECK (assessment_confidence IN ('HIGH', 'STANDARD', 'LIMITED')),
  global_limitations JSONB NOT NULL DEFAULT '[]'::jsonb,
  safety_flags JSONB NOT NULL DEFAULT '[]'::jsonb,
  overall_score INTEGER NULL CHECK (overall_score BETWEEN 0 AND 100),
  overall_band TEXT NULL,
  archetype_code TEXT NULL,
  archetype_match_score NUMERIC(5,2) NULL CHECK (archetype_match_score BETWEEN 0 AND 100),
  archetype_second_match_score NUMERIC(5,2) NULL CHECK (archetype_second_match_score BETWEEN 0 AND 100),
  archetype_gap NUMERIC(5,2) NULL CHECK (archetype_gap >= 0),
  archetype_confidence TEXT NULL CHECK (archetype_confidence IN ('HIGH', 'STANDARD', 'FALLBACK')),
  archetype_engine_version TEXT NULL,
  source_system TEXT NOT NULL DEFAULT 'GLOW_V1',
  historical_import BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (assessment_status <> 'VALID' OR overall_score IS NOT NULL),
  CHECK (assessment_status <> 'VALID' OR photo_quality_status = 'PASS')
)